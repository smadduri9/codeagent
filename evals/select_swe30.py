"""Pick the SWE-bench Lite subset in evals/slices/swe30.txt.

Rules: repositories that run under pytest without Docker or C builds; 1-3
FAIL_TO_PASS tests; ten tasks per difficulty tier by reference-patch size
(easy <=4 changed lines, medium 5-10, hard >10); per-repository caps so one
project does not dominate; IDs sorted, then shuffled with a fixed seed.

Usage: python -m evals.select_swe30 <swe_bench_lite_test.jsonl> <out.txt>
"""

from __future__ import annotations

import json
import random
import sys
from collections import Counter
from pathlib import Path
from typing import Any

CAPS = {
    "sympy/sympy": 12,
    "pytest-dev/pytest": 8,
    "sphinx-doc/sphinx": 5,
    "pylint-dev/pylint": 4,
    "pallets/flask": 3,
}
SEED = 20261014
TIERS = ("easy", "medium", "hard")


def _tests(value: Any) -> list[str]:
    return json.loads(value) if isinstance(value, str) else list(value or [])


def patch_size(patch: str) -> int:
    """Changed lines in a unified diff, excluding file headers."""
    return sum(
        1 for line in patch.splitlines() if line[:1] in "+-" and not line.startswith(("+++", "---"))
    )


def tier(size: int) -> str:
    return "easy" if size <= 4 else ("medium" if size <= 10 else "hard")


def select(
    rows: list[dict[str, Any]],
    *,
    caps: dict[str, int] = CAPS,
    seed: int = SEED,
    per_tier: int = 10,
) -> dict[str, list[str]]:
    eligible = sorted(
        (r for r in rows if r["repo"] in caps and 1 <= len(_tests(r["FAIL_TO_PASS"])) <= 3),
        key=lambda r: r["instance_id"],
    )
    rng = random.Random(seed)
    pools = {t: [r for r in eligible if tier(patch_size(r["patch"])) == t] for t in TIERS}
    for name in TIERS:
        rng.shuffle(pools[name])
    used: Counter[str] = Counter()
    picked: dict[str, list[str]] = {t: [] for t in TIERS}
    for name in ("hard", "medium", "easy"):  # hard first: it has the fewest candidates
        for row in pools[name]:
            if len(picked[name]) == per_tier:
                break
            if used[row["repo"]] < caps[row["repo"]]:
                picked[name].append(row["instance_id"])
                used[row["repo"]] += 1
    return picked


def main(argv: list[str]) -> None:
    rows = [json.loads(line) for line in Path(argv[1]).read_text().splitlines() if line.strip()]
    picked = select(rows)
    lines = [
        "# SWE-bench Lite subset: 10 easy / 10 medium / 10 hard by reference-patch size.",
        f"# Seed {SEED}. Generated by evals/select_swe30.py; caps {CAPS}.",
    ]
    for name in TIERS:
        lines.append(f"# {name}")
        lines.extend(picked[name])
    Path(argv[2]).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
